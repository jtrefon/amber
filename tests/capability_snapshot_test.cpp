// The capability inventory the 0.9 journey matrix is checked against.
//
// The matrix must cover every bundled plugin capability and every tool the
// default composition registers. Enumerating those from a hand-written list
// would make the matrix agree with the list rather than with the product, so
// this test reads the real declarations and pins them to a committed snapshot:
// a capability that appears or disappears without a reviewed snapshot update
// fails `make test`, and the Python gate then holds the matrix to the snapshot.

#include "agent.h"
#include "agent/job.h"
#include "agent/plugin_capability.h"
#include "agent/plugin_console.h"
#include "agent/plugins_bundled.h"
#include "agent/todo.h"
#include "test_util.h"

#include <cstdlib>
#include <fstream>
#include <map>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace {

constexpr const char* kSnapshotPath = "tests/capability_snapshot.txt";

std::string read_file(const std::string& path) {
    std::ifstream in(path, std::ios::binary);
    std::ostringstream out;
    out << in.rdbuf();
    return out.str();
}

// One line per plugin, capability and default tool. Sorted so an unrelated
// declaration reorder does not churn the snapshot; the matrix cares about the
// set, not the order a plugin happens to build it in.
std::vector<std::string> snapshot_lines() {
    std::map<std::string, std::shared_ptr<agent::IPlugin>> plugins;
    for (auto& plugin : agent::make_bundled_plugins())
        plugins.emplace(plugin->id(), plugin);

    std::vector<std::string> lines;
    std::set<std::string> capabilities;
    for (const auto& entry : plugins) {
        lines.push_back("plugin\t" + entry.first);
        for (const auto& capability : entry.second->capabilities()) {
            std::ostringstream line;
            line << "capability\t" << entry.first << '\t'
                 << agent::capability_kind_name(capability->kind()) << '\t' << capability->name();
            capabilities.insert(line.str());
        }
    }
    lines.insert(lines.end(), capabilities.begin(), capabilities.end());

    agent::JobService jobs;
    agent::TodoStore todos;
    agent::CancellationToken cancel;
    agent::ToolRegistry bare;
    agent::register_default_tools(bare, jobs, todos, cancel);
    std::set<std::string> tools;
    for (const auto& tool : bare.snapshot_tools())
        tools.insert("default-tool\t" + tool->name());
    lines.insert(lines.end(), tools.begin(), tools.end());
    return lines;
}

std::string render(const std::vector<std::string>& lines) {
    std::ostringstream out;
    out << "# Generated by ./run_tests capability_snapshot with\n"
        << "# AMBER_UPDATE_CAPABILITY_SNAPSHOT=1. Every bundled plugin, every capability it\n"
        << "# declares, and every tool the bare-host default composition registers.\n"
        << "# Reviewed updates: `make capability-snapshot-update`.\n";
    for (const auto& line : lines)
        out << line << '\n';
    return out.str();
}

std::vector<std::string> split_lines(const std::string& text) {
    std::vector<std::string> lines;
    std::istringstream in(text);
    std::string line;
    while (std::getline(in, line))
        if (!line.empty() && line[0] != '#')
            lines.push_back(line);
    return lines;
}

// Lines present on one side only, so a failure names the drift instead of
// printing two hundred lines that differ somewhere.
std::vector<std::string> difference(const std::vector<std::string>& left,
                                    const std::vector<std::string>& right) {
    std::vector<std::string> out;
    std::set<std::string> right_set(right.begin(), right.end());
    for (const auto& line : left)
        if (right_set.find(line) == right_set.end())
            out.push_back(line);
    return out;
}

std::string join(const std::vector<std::string>& lines) {
    std::string out;
    for (const auto& line : lines)
        out += (out.empty() ? "" : "\n") + line;
    return out;
}

} // namespace

TEST(capability_snapshot_matches_bundled_plugins) {
    const std::string actual = render(snapshot_lines());
    if (const char* update = std::getenv("AMBER_UPDATE_CAPABILITY_SNAPSHOT");
        update != nullptr && std::string(update) == "1") {
        std::ofstream out(kSnapshotPath, std::ios::binary);
        ASSERT(out.good());
        out << actual;
        ASSERT(out.good());
        return;
    }

    const std::string committed = read_file(kSnapshotPath);
    ASSERT_FALSE(committed.empty());
    const std::vector<std::string> expected = split_lines(committed);
    const std::vector<std::string> live = split_lines(actual);
    const std::vector<std::string> missing = difference(live, expected);
    const std::vector<std::string> stale = difference(expected, live);
    if (missing.empty() && stale.empty())
        return;
    std::ostringstream message;
    message << "capability snapshot is stale; run `make capability-snapshot-update`\n";
    if (!missing.empty())
        message << "declared but not recorded:\n" << join(missing) << "\n";
    if (!stale.empty())
        message << "recorded but no longer declared:\n" << join(stale) << "\n";
    agent::test::fail(message.str());
}
